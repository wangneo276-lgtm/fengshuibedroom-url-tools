pub fn locale_url(locale: &str, name: &str) -> Result<String, String> {
    if !has(LOCALES, locale) { return Err(format!("unknown locale: {locale}")); }
    let path = page_path(name)?;
    if locale == "en" { return canonical_url(path); }
    let localized = if path == "/" { format!("/{locale}") } else { format!("/{locale}{path}") };
    canonical_url(&localized)
}

